/**
 * Тип правила Daitch-Mokotoff — массив из трёх числовых значений,
 * определяющих фонетический код в зависимости от контекста:
 *
 * - `[0]` — если символ в начале слова
 * - `[1]` — если символ перед гласной (A, E, I, O, U)
 * - `[2]` — во всех остальных случаях
 *
 * Значение `-1` — пропуск.
 *
 * @since 0.4.0
 *
 **/
export type DaitchMokotoffRule = [number, number, number];

/**
 * Тип узла дерева правил Daitch-Mokotoff.
 *
 * Узел может быть:
 * - Массивом правил — например, для альтернативных путей (латиница/кириллица)
 * - Объектом с опциональным ключом `'0'`, содержащим базовое правило
 * - Объектом с опциональным ключом `'1'`, используемым для кириллических вариантов
 * - Объектом, где строковые ключи — следующие символы, а значения — вложенные узлы
 *
 * Это позволяет строить древовидные правила для комбинаций букв (например, `QU`, `SH`, `TH`).
 *
 * @since 0.4.0
 *
 **/
export type DaitchMokotoffNode
  = | DaitchMokotoffRule[]
    | { 0?: DaitchMokotoffRule }
    | { 1?: DaitchMokotoffRule }
    | { [key: string]: DaitchMokotoffNode };

/**
 * Тип для фонетического кода — строка, гарантированно содержащая 6 цифр.
 *
 * Используется для маркировки результата функции `daitchMokotoffLite`,
 * чтобы отличать обычные строки от валидных фонетических кодов.
 *
 * @example
 * ```ts
 * '550000' as PhoneticCode
 * ```
 *
 * @since 0.4.0
 *
 **/
export type PhoneticCode = Branded<string, 'PhoneticCode'>;
